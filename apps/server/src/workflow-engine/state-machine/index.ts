export const TASK_WORKFLOW_STATUS = {
  DRAFT: "DRAFT",
  SUBMITTED: "SUBMITTED",
  OPS_REJECTED: "OPS_REJECTED",
  OPS_APPROVED: "OPS_APPROVED",
  DESIGN_ASSIGNED: "DESIGN_ASSIGNED",
  IN_DESIGN: "IN_DESIGN",
  DESIGN_REVIEW: "DESIGN_REVIEW",
  DESIGN_APPROVED: "DESIGN_APPROVED",
  COMPLETED: "COMPLETED",
  CANCELLED: "CANCELLED",
} as const;

export type TaskWorkflowStatus = (typeof TASK_WORKFLOW_STATUS)[keyof typeof TASK_WORKFLOW_STATUS];

export const IMAGE_TASK_STATUS = {
  WAITING_OPS_APPROVAL: "WAITING_OPS_APPROVAL",
  PENDING_ASSIGNMENT: "PENDING_ASSIGNMENT",
  NOT_STARTED: "NOT_STARTED",
  IN_PROGRESS: "IN_PROGRESS",
  SUBMITTED_FOR_REVIEW: "SUBMITTED_FOR_REVIEW",
  REVISION_REQUIRED: "REVISION_REQUIRED",
  APPROVED: "APPROVED",
  COMPLETED: "COMPLETED",
} as const;

export type ImageTaskStatusEnum = (typeof IMAGE_TASK_STATUS)[keyof typeof IMAGE_TASK_STATUS];

const TASK_TRANSITIONS: Record<string, string[]> = {
  [TASK_WORKFLOW_STATUS.DRAFT]: [TASK_WORKFLOW_STATUS.SUBMITTED],
  [TASK_WORKFLOW_STATUS.OPS_REJECTED]: [TASK_WORKFLOW_STATUS.SUBMITTED],
  [TASK_WORKFLOW_STATUS.SUBMITTED]: [TASK_WORKFLOW_STATUS.DRAFT, TASK_WORKFLOW_STATUS.OPS_APPROVED, TASK_WORKFLOW_STATUS.OPS_REJECTED],
  [TASK_WORKFLOW_STATUS.OPS_APPROVED]: [TASK_WORKFLOW_STATUS.DESIGN_ASSIGNED, TASK_WORKFLOW_STATUS.IN_DESIGN],
  [TASK_WORKFLOW_STATUS.DESIGN_ASSIGNED]: [TASK_WORKFLOW_STATUS.IN_DESIGN],
  [TASK_WORKFLOW_STATUS.IN_DESIGN]: [TASK_WORKFLOW_STATUS.DESIGN_REVIEW, TASK_WORKFLOW_STATUS.DESIGN_APPROVED],
  [TASK_WORKFLOW_STATUS.DESIGN_REVIEW]: [TASK_WORKFLOW_STATUS.IN_DESIGN, TASK_WORKFLOW_STATUS.DESIGN_APPROVED],
  [TASK_WORKFLOW_STATUS.DESIGN_APPROVED]: [],
  [TASK_WORKFLOW_STATUS.COMPLETED]: [],
  [TASK_WORKFLOW_STATUS.CANCELLED]: [],
};

const IMAGE_TASK_TRANSITIONS: Record<string, string[]> = {
  [IMAGE_TASK_STATUS.WAITING_OPS_APPROVAL]: [IMAGE_TASK_STATUS.PENDING_ASSIGNMENT],
  [IMAGE_TASK_STATUS.PENDING_ASSIGNMENT]: [IMAGE_TASK_STATUS.NOT_STARTED],
  [IMAGE_TASK_STATUS.NOT_STARTED]: [IMAGE_TASK_STATUS.IN_PROGRESS],
  [IMAGE_TASK_STATUS.IN_PROGRESS]: [IMAGE_TASK_STATUS.SUBMITTED_FOR_REVIEW, IMAGE_TASK_STATUS.COMPLETED],
  [IMAGE_TASK_STATUS.SUBMITTED_FOR_REVIEW]: [IMAGE_TASK_STATUS.REVISION_REQUIRED, IMAGE_TASK_STATUS.APPROVED],
  [IMAGE_TASK_STATUS.REVISION_REQUIRED]: [IMAGE_TASK_STATUS.IN_PROGRESS],
  [IMAGE_TASK_STATUS.APPROVED]: [IMAGE_TASK_STATUS.COMPLETED],
  [IMAGE_TASK_STATUS.COMPLETED]: [],
};

export class StateMachine {
  static canTransition(current: string, next: string, entityType: "task" | "image_task"): boolean {
    const transitions = entityType === "task" ? TASK_TRANSITIONS : IMAGE_TASK_TRANSITIONS;
    return (transitions[current] || []).includes(next);
  }

  static getAllowedTransitions(current: string, entityType: "task" | "image_task"): string[] {
    return (entityType === "task" ? TASK_TRANSITIONS : IMAGE_TASK_TRANSITIONS)[current] || [];
  }

  static isValidStatus(status: string, entityType: "task" | "image_task"): boolean {
    const valid = entityType === "task" ? Object.values(TASK_WORKFLOW_STATUS) : Object.values(IMAGE_TASK_STATUS);
    return valid.includes(status as any);
  }

  static calcTaskWorkflowStatus(imageStatuses: string[]): TaskWorkflowStatus {
    if (!imageStatuses || imageStatuses.length === 0) return TASK_WORKFLOW_STATUS.OPS_APPROVED;
    if (imageStatuses.every(s => s === IMAGE_TASK_STATUS.COMPLETED || s === IMAGE_TASK_STATUS.APPROVED)) return TASK_WORKFLOW_STATUS.DESIGN_APPROVED;
    if (imageStatuses.some(s => s === IMAGE_TASK_STATUS.SUBMITTED_FOR_REVIEW)) return TASK_WORKFLOW_STATUS.DESIGN_REVIEW;
    if (imageStatuses.some(s => s === IMAGE_TASK_STATUS.NOT_STARTED || s === IMAGE_TASK_STATUS.IN_PROGRESS || s === IMAGE_TASK_STATUS.REVISION_REQUIRED)) return TASK_WORKFLOW_STATUS.IN_DESIGN;
    return TASK_WORKFLOW_STATUS.OPS_APPROVED;
  }
}
