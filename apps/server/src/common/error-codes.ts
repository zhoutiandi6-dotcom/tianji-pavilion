// ===== 天机阁 统一业务错误码 =====

export enum ErrorCode {
  // Auth
  AUTH_UNAUTHORIZED = "AUTH_UNAUTHORIZED",
  AUTH_FORBIDDEN = "AUTH_FORBIDDEN",
  AUTH_TOKEN_EXPIRED = "AUTH_TOKEN_EXPIRED",
  AUTH_INVALID_CREDENTIALS = "AUTH_INVALID_CREDENTIALS",
  AUTH_ACCOUNT_LOCKED = "AUTH_ACCOUNT_LOCKED",
  AUTH_ACCOUNT_DISABLED = "AUTH_ACCOUNT_DISABLED",

  // User
  USER_NOT_FOUND = "USER_NOT_FOUND",
  USER_ALREADY_EXISTS = "USER_ALREADY_EXISTS",
  USER_DISABLED = "USER_DISABLED",
  USER_OWNER_PROTECTED = "USER_OWNER_PROTECTED",

  // Role
  ROLE_NOT_FOUND = "ROLE_NOT_FOUND",
  ROLE_FORBIDDEN = "ROLE_FORBIDDEN",

  // Task / Workflow
  WORKFLOW_NOT_FOUND = "WORKFLOW_NOT_FOUND",
  WORKFLOW_INVALID_TRANSITION = "WORKFLOW_INVALID_TRANSITION",
  WORKFLOW_ALREADY_APPROVED = "WORKFLOW_ALREADY_APPROVED",
  WORKFLOW_NOT_APPROVED = "WORKFLOW_NOT_APPROVED",

  // Image Task
  IMAGE_TASK_NOT_FOUND = "IMAGE_TASK_NOT_FOUND",
  IMAGE_TASK_NOT_OWNED = "IMAGE_TASK_NOT_OWNED",

  // Validation
  VALIDATION_ERROR = "VALIDATION_ERROR",
  BAD_REQUEST = "BAD_REQUEST",

  // System
  SYSTEM_INITIALIZED = "SYSTEM_INITIALIZED",
  SYSTEM_NOT_INITIALIZED = "SYSTEM_NOT_INITIALIZED",
  SYSTEM_ERROR = "SYSTEM_ERROR",

  // Generic
  NOT_FOUND = "NOT_FOUND",
  CONFLICT = "CONFLICT",
  FORBIDDEN = "FORBIDDEN",
  OK = "OK",
}

export function httpStatusToErrorCode(status: number): string {
  switch (status) {
    case 400: return ErrorCode.BAD_REQUEST;
    case 401: return ErrorCode.AUTH_UNAUTHORIZED;
    case 403: return ErrorCode.AUTH_FORBIDDEN;
    case 404: return ErrorCode.NOT_FOUND;
    case 409: return ErrorCode.CONFLICT;
    default: return ErrorCode.SYSTEM_ERROR;
  }
}
